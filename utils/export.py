"""
Export Utilities — Markdown and PDF export for reports.
"""

try:
    import markdown
except ImportError:
    markdown = None
from typing import Optional
from tools.citations import CitationTracker


def export_markdown(report_md: str, tracker: Optional[CitationTracker] = None) -> bytes:
    """
    Export report as markdown with frontmatter and citations.
    Returns bytes for download.
    """
    from datetime import datetime

    # Ensure tracker citations are in the markdown
    if tracker and tracker.citations:
        tracker_citations = tracker.format_markdown()
        if tracker_citations and tracker_citations not in report_md:
            report_md = report_md + tracker_citations

    # Build frontmatter
    frontmatter = f"""---
title: "Kimi Research Report"
topic: "{report_md.split(chr(10))[0].replace('#', '').strip() if report_md else 'Research'}"
date: "{datetime.now().isoformat()}"
generator: "Kimi Multi-Agent Research Assistant"
agents: ["Researcher", "Web Searcher", "Analyst", "Summarizer"]
---

"""

    full_md = frontmatter + report_md
    return full_md.encode("utf-8")


def export_pdf(report_md: str, tracker: Optional[CitationTracker] = None) -> bytes:
    """
    Export report as PDF using WeasyPrint.
    Returns PDF bytes for download.
    """
    try:
        from weasyprint import HTML, CSS
        from weasyprint.text.fonts import FontConfiguration
    except ImportError:
        raise RuntimeError("WeasyPrint not installed. Run: pip install weasyprint")

    # Build full HTML - ensure tracker citations are included
    if tracker and tracker.citations:
        tracker_citations = tracker.format_markdown()
        if tracker_citations and tracker_citations not in report_md:
            report_md = report_md + tracker_citations

    html_content = _build_pdf_html(report_md, tracker)

    # Create PDF
    font_config = FontConfiguration()
    html = HTML(string=html_content)
    css = CSS(string=_get_pdf_css(), font_config=font_config)

    pdf_bytes = html.write_pdf(stylesheets=[css], font_config=font_config)
    return pdf_bytes


def _build_pdf_html(report_md: str, tracker: Optional[CitationTracker]) -> str:
    """Build complete HTML document for PDF generation."""
    # Convert markdown to HTML
    md_html = markdown.markdown(
        report_md,
        extensions=["fenced_code", "tables", "toc", "attr_list", "codehilite"],
    )

    # Add citations
    citations_html = ""
    if tracker and tracker.citations:
        citations_html = "<hr>\n<h2>Sources</h2>\n<ol>\n"
        for i, (cit_id, entry) in enumerate(tracker.citations.items(), 1):
            citations_html += (
                f"<li><strong>{entry.title}</strong> — "
                f"<a href='{entry.url}'>{entry.url}</a>  \n"
                f"Relevance: {entry.relevance_pct}%</li>\n"
            )
            if entry.snippet:
                citations_html += f"<blockquote>{entry.snippet[:300]}...</blockquote>\n"
        citations_html += "</ol>"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Kimi Research Report</title>
</head>
<body>
    <div class="report-container">
        <header class="report-header">
            <h1>Kimi Research Report</h1>
            <p class="meta">Generated by Kimi Multi-Agent Research Assistant</p>
        </header>
        <main class="report-body">
            {md_html}
            {citations_html}
        </main>
        <footer class="report-footer">
            <p>Generated on {__import__('datetime').datetime.now().strftime('%Y-%m-%d %H:%M')}</p>
        </footer>
    </div>
</body>
</html>"""


