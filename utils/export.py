    """Export as standalone HTML file."""
    html = _build_pdf_html(report_md, tracker)
    # Add embedded CSS
    css = _get_pdf_css()
    full_html = html.replace("</head>", f"<style>{css}</style></head>")
    return full_html.encode("utf-8")